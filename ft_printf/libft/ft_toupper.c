int	ft_toupper(int c)
{
	if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z'))
	{
		if ((c >= 'A' && c <= 'Z'))
			return (c);
		else
			return (c - 32);
	}
	return (c);
}
